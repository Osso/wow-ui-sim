#!/usr/bin/env python3
"""Export the Retail UIScriptedAnimationEffect DB2 rows into the profile catalog."""

import argparse
import csv
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import struct
import sys

LAYOUT = 0x016692F7
FILE_DATA_ID = 3556601
FIELD_NAMES = (
    "Visual",
    "VisualScale",
    "Duration",
    "Trajectory",
    "StartSoundKitID",
    "FinishSoundKitID",
    "StartBehavior",
    "FinishBehavior",
    "FinishEffectID",
    "YawRadians",
    "PitchRadians",
    "RollRadians",
    "OffsetX",
    "OffsetY",
    "OffsetZ",
    "AnimationSpeed",
    "Animation",
    "AnimationStartOffset",
    "Alpha",
    "StartAlphaFade",
    "StartAlphaFadeDuration",
    "EndAlphaFade",
    "EndAlphaFadeDuration",
    "LoopingSoundKitID",
    "ParticleOverrideScale",
    "Flags",
)
FLOAT_FIELDS = range(9, 16)
RUST_FIELDS = (
    ("visual", "u32"),
    ("visual_scale", "i32"),
    ("duration", "i32"),
    ("trajectory", "u32"),
    ("start_sound_kit_id", "u32"),
    ("finish_sound_kit_id", "u32"),
    ("start_behavior", "u32"),
    ("finish_behavior", "u32"),
    ("finish_effect_id", "u32"),
    ("yaw_radians", "f32"),
    ("pitch_radians", "f32"),
    ("roll_radians", "f32"),
    ("offset_x", "f32"),
    ("offset_y", "f32"),
    ("offset_z", "f32"),
    ("animation_speed", "f32"),
    ("animation", "u32"),
    ("animation_start_offset", "i32"),
    ("alpha", "i32"),
    ("start_alpha_fade", "i32"),
    ("start_alpha_fade_duration", "i32"),
    ("end_alpha_fade", "i32"),
    ("end_alpha_fade_duration", "i32"),
    ("looping_sound_kit_id", "u32"),
    ("particle_override_scale", "i32"),
    ("flags", "u32"),
)


def load_exporter(path):
    spec = importlib.util.spec_from_file_location("wow_ui_sim_db2_exporter", path)
    if spec is None or spec.loader is None:
        raise ValueError(f"cannot load DB2 exporter {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    if not hasattr(module, "read_wdc5"):
        raise ValueError(f"{path}: missing read_wdc5")
    return module


def decode_rows(data, exporter):
    if data[:4] != b"WDC5":
        raise ValueError("expected WDC5 DB2")
    actual_layout = struct.unpack_from("<I", data, 156)[0]
    if actual_layout != LAYOUT:
        raise ValueError(f"layout {actual_layout:08X}, expected {LAYOUT:08X}")
    records, unreadable, _, _ = exporter.read_wdc5(data, LAYOUT, 0)
    if unreadable or not records:
        raise ValueError(f"unexpected unreadable/empty rows: {unreadable}/{len(records)}")
    rows = []
    for row_id, (values, _, _) in sorted(records.items()):
        if len(values) != len(FIELD_NAMES):
            raise ValueError(f"row {row_id}: expected 26 fields, found {len(values)}")
        floats = [struct.unpack("<f", struct.pack("<I", values[i]))[0] for i in FLOAT_FIELDS]
        if any(not math.isfinite(value) for value in floats):
            raise ValueError(f"row {row_id}: non-finite float")
        rows.append((row_id, *values))
    return rows


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as output:
        writer = csv.writer(output, lineterminator="\n")
        writer.writerow(("ID", *FIELD_NAMES))
        for row in rows:
            writer.writerow((row[0], *(format(struct.unpack("<f", struct.pack("<I", row[i + 1]))[0], ".9g")
                                          if i in FLOAT_FIELDS else row[i + 1]
                                          for i in range(len(FIELD_NAMES)))))


def write_rust(path, rows, build, build_key, csv_hash):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/gen_scripted_animation_effects.py; do not edit.",
        f"// Retail build {build}; build key {build_key}; CSV SHA-256 {csv_hash}.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct Db2Row {",
        "    pub id: u32,",
    ]
    lines.extend(f"    pub {name}: {kind}," for name, kind in RUST_FIELDS)
    lines.extend(["}", "", "#[rustfmt::skip]", "pub static ROWS: &[Db2Row] = &["])
    for row in rows:
        values = [str(row[0])]
        for index, (_, kind) in enumerate(RUST_FIELDS):
            raw = row[index + 1]
            value = f"f32::from_bits(0x{raw:08x})" if kind == "f32" else str(raw)
            values.append(value)
        fields = ", ".join(f"{name}: {value}" for (name, _), value in zip((("id", "u32"), *RUST_FIELDS), values))
        lines.append(f"    Db2Row {{ {fields} }},")
    lines.extend(["];"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_provenance(path, args, data, rows, csv_path, exporter_path):
    exporter_hash = hashlib.sha256(exporter_path.read_bytes()).hexdigest()
    provenance = {
        "profile": "retail",
        "product": "wow",
        "build": args.build,
        "build_key": args.build_key,
        "source": "local CASC via wow-cli casc extract-fdid",
        "table": "UIScriptedAnimationEffect",
        "file_data_id": FILE_DATA_ID,
        "layout": f"{LAYOUT:08X}",
        "db2_sha256": hashlib.sha256(data).hexdigest(),
        "row_count": len(rows),
        "unreadable_rows": 0,
        "csv_sha256": hashlib.sha256(csv_path.read_bytes()).hexdigest(),
        "exporter": "game-engine/scripts/export_db2_csv.py",
        "exporter_sha256": exporter_hash,
        "field_order": ["ID", *FIELD_NAMES],
        "mapping": "DB2 values are retained in source units; conversion to the Lua API is inferred separately (R88fl, native evidence pending).",
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db2", type=Path, required=True)
    parser.add_argument("--exporter", type=Path, required=True)
    parser.add_argument("--build", required=True)
    parser.add_argument("--build-key", required=True)
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument("--rust", type=Path, required=True)
    parser.add_argument("--provenance", type=Path, required=True)
    args = parser.parse_args()
    data = args.db2.read_bytes()
    exporter = load_exporter(args.exporter)
    rows = decode_rows(data, exporter)
    write_csv(args.csv, rows)
    csv_hash = hashlib.sha256(args.csv.read_bytes()).hexdigest()
    write_rust(args.rust, rows, args.build, args.build_key, csv_hash)
    write_provenance(args.provenance, args, data, rows, args.csv, args.exporter)
    print(f"generated {len(rows)} Retail UIScriptedAnimationEffect rows")


if __name__ == "__main__":
    main()

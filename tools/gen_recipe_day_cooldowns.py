#!/usr/bin/env python3
"""Generate recipe day-cooldown spell IDs from pinned Retail DB2 CSVs."""

import argparse
import csv
import hashlib
from pathlib import Path


def rows(path):
    with path.open(newline="", encoding="utf-8-sig") as source:
        yield from csv.DictReader(source)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--spell-category", type=Path, required=True)
    parser.add_argument("--spell-categories", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    flags = {}
    for row in rows(args.spell_category):
        category = int(row["ID"])
        if category in flags:
            raise ValueError(f"duplicate SpellCategory {category}")
        flags[category] = int(row["Flags"])

    day_spells = set()
    categories_by_spell = {}
    for row in rows(args.spell_categories):
        if int(row["DifficultyID"]) != 0:
            continue
        spell, category = int(row["SpellID"]), int(row["Category"])
        if spell in categories_by_spell and categories_by_spell[spell] != category:
            raise ValueError(f"conflicting base-difficulty categories for spell {spell}")
        categories_by_spell[spell] = category
        if category and category not in flags:
            raise ValueError(f"missing SpellCategory {category}")
        if flags.get(category, 0) & 8:
            day_spells.add(spell)

    category_hash = hashlib.sha256(args.spell_category.read_bytes()).hexdigest()
    categories_hash = hashlib.sha256(args.spell_categories.read_bytes()).hexdigest()
    lines = [
        "//! PROVENANCE: pinned Retail 12.1.5.70391 SpellCategory and SpellCategories CSVs.",
        f"//! SpellCategory SHA256: {category_hash}",
        f"//! SpellCategories SHA256: {categories_hash}",
        "//! 70688 record equality is unknown. Generated by tools/gen_recipe_day_cooldowns.py.",
        "//! Selection: base-difficulty SpellCategories.Category -> SpellCategory.Flags & 8.",
        "",
        "pub(super) static DAY_COOLDOWN_SPELLS: &[u32] = &[",
    ]
    lines.extend(f"    {spell}," for spell in sorted(day_spells))
    lines.extend(["];", ""])
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(day_spells)} day-cooldown spell IDs")


if __name__ == "__main__":
    main()

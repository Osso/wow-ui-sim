#!/usr/bin/env python3
"""Generate the PTR event catalog from the pinned Blizzard UI cache."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADDONS = Path.home() / ".cache/wow-ui-sim/blizzard-ui/ptr/AddOns"
EVENT = re.compile(r'Type\s*=\s*"Event"\s*,\s*LiteralName\s*=\s*"([A-Z0-9_]+)"')


def generate(addons: Path) -> str:
    files = sorted((addons / "Blizzard_APIDocumentationGenerated").glob("*.lua"))
    if not files:
        raise ValueError("no PTR documentation files found")
    provenance = dict(line.split("=", 1) for line in (addons / ".wow-ui-sim-blizzard-ui-provenance").read_text().splitlines())
    if provenance.get("profile") != "ptr":
        raise ValueError("documentation provenance is not PTR")
    events = set()
    for path in files:
        content = path.read_text()
        found = EVENT.findall(content)
        if len(found) != len(re.findall(r'Type\s*=\s*"Event"', content)):
            raise ValueError(f"unrecognized event declaration in {path}")
        events.update(found)
    # The runtime-selected glue consumers register these events on load.
    # A full selected-consumer scan requires TOC and XML loading semantics.
    consumer_events = {
        "CHARACTER_UNDELETE_STARTED": "Blizzard_GlueXML/Mainline/CharacterSelect.lua:40",
        "CHARACTER_DECLINE_RESULT": "Blizzard_DeclensionFrame/Mainline/DeclensionFrameGlue.lua:13",
        "CHARACTER_DECLINE_IN_PROGRESS": "Blizzard_DeclensionFrame/Mainline/DeclensionFrameGlue.lua:14",
        "FORCE_DECLINE_CHARACTER": "Blizzard_DeclensionFrame/Mainline/DeclensionFrameGlue.lua:12",
    }
    events.update(consumer_events)
    lines = [
        "//! Generated by tools/gen_ptr_documented_events.py; do not edit.",
        "//! Source: ~/.cache/wow-ui-sim/blizzard-ui/ptr/AddOns/Blizzard_APIDocumentationGenerated/*.lua",
        f"//! Build: {provenance['version']}; files: {len(files)}; events: {len(events)}.",
        "", "pub(super) const EVENTS: &[&str] = &["]
    lines.extend(
        f'    "{event}",' + (f' // {consumer_events[event]}' if event in consumer_events else "")
        for event in sorted(events)
    )
    return "\n".join(lines + ["];", ""])


if __name__ == "__main__":
    (ROOT / "src/event/ptr_documented_events.rs").write_text(generate(ADDONS))

#!/usr/bin/env python3
"""Behavioral tests for the projected Retail PvP talent export."""

import csv
import importlib.util
from pathlib import Path
import tempfile
import unittest

SPEC = importlib.util.spec_from_file_location(
    "gen_pvp_talent_catalog", Path(__file__).with_name("gen_pvp_talent_catalog.py")
)
generator = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(generator)


class PvpTalentCatalogTests(unittest.TestCase):
    def read_rows(self, header, rows):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "PvpTalent.csv"
            with path.open("w", newline="") as output:
                writer = csv.writer(output)
                writer.writerow(header)
                writer.writerows(rows)
            return generator.read_rows(path)

    def test_named_columns_preserve_zero_and_sort_talent_ids(self):
        rows = self.read_rows(
            ["LevelRequired", "OverridesSpellID", "ID", "SpellID", "TalentSlotMask"],
            [[20, 0, 24, 236077, 14], [10, 116, 12, 133, 1]],
        )
        self.assertEqual(rows, [(12, 133, 116, 10, 1), (24, 236077, 0, 20, 14)])
        self.assertEqual(
            generator.render_rust(rows, "12.1.5.70783", "abc"),
            "// Generated by tools/gen_pvp_talent_catalog.py; do not edit.\n"
            "// Local Retail build 12.1.5.70783; projected CSV SHA-256: abc.\n"
            "// (talent ID, SpellID, OverridesSpellID, LevelRequired, TalentSlotMask).\n"
            "pub(super) const ROWS: &[(i32, u32, u32, i32, u8)] = &[\n"
            "    (12, 133, 116, 10, 1),\n"
            "    (24, 236077, 0, 20, 14),\n"
            "];\n",
        )

    def test_duplicate_talent_ids_are_rejected(self):
        with self.assertRaisesRegex(ValueError, "duplicate talent ID 24"):
            self.read_rows(generator.FIELDS, [[24, 236077, 0, 20, 14]] * 2)

    def test_missing_columns_and_out_of_range_fields_are_rejected(self):
        with self.assertRaisesRegex(ValueError, "missing columns"):
            self.read_rows(["ID", "SpellID"], [[24, 236077]])
        for index, value in [(0, 1 << 31), (1, -1), (2, 1 << 32), (3, 1 << 31), (4, 256)]:
            with self.subTest(index=index):
                row = [24, 236077, 0, 20, 14]
                row[index] = value
                with self.assertRaisesRegex(ValueError, "out of range"):
                    self.read_rows(generator.FIELDS, [row])

    def test_empty_export_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "no rows"):
            self.read_rows(generator.FIELDS, [])


if __name__ == "__main__":
    unittest.main()

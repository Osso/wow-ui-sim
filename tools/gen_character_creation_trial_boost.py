#!/usr/bin/env python3
"""Generate Retail CharacterServiceInfo rows from the pinned DB2 CSV export."""

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/character-service-info"
SOURCE = DATA / "retail-12.1.5.70783.csv"
DEFINITION = DATA / "CharacterServiceInfo.dbd"
PROVENANCE = DATA / "retail-12.1.5.70783.provenance.json"
OUTPUT = ROOT / "src/c_api/c_character_creation_trial_boost_data.rs"
TABLE = "CharacterServiceInfo"
BUILD = "12.1.5.70783"
LAYOUT_HASH = "7DEDBFA6"
FIELDS = ("ServiceType", "BoostType", "BoostLevel")


def read_export_rows():
    provenance = json.loads(PROVENANCE.read_text(encoding="utf-8"))
    if provenance["table"] != TABLE or provenance["build"] != BUILD:
        raise ValueError(f"{PROVENANCE}: table or build does not match this generator")
    if provenance["db2"]["layout_hash"] != LAYOUT_HASH:
        raise ValueError(f"{PROVENANCE}: DB2 layout does not match this generator")
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    if source_hash != provenance["csv_sha256"]:
        raise ValueError(f"{SOURCE}: SHA-256 does not match its provenance")

    definition_hash = hashlib.sha256(DEFINITION.read_bytes()).hexdigest()
    if definition_hash != provenance["definitions"]["sha256"]:
        raise ValueError(f"{DEFINITION}: SHA-256 does not match its provenance")

    rows = []
    with SOURCE.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if not set(FIELDS).issubset(reader.fieldnames or ()):
            raise ValueError(f"{SOURCE}: missing required CharacterServiceInfo columns")
        for line, row in enumerate(reader, start=2):
            try:
                values = tuple(int(row[field]) for field in FIELDS)
            except (TypeError, ValueError) as error:
                raise ValueError(f"{SOURCE}:{line}: invalid numeric service row") from error
            if any(not -(1 << 31) <= value < (1 << 31) for value in values):
                raise ValueError(f"{SOURCE}:{line}: value is outside signed 32-bit range")
            rows.append(values)

    if len(rows) != provenance["row_count"]:
        raise ValueError(f"{SOURCE}: row count does not match its provenance")
    if provenance["unreadable_records"] != 0:
        raise ValueError(f"{SOURCE}: source export contains unreadable records")
    return rows, source_hash, definition_hash


def render_rust(rows, source_hash, definition_hash):
    lines = [
        "// Generated by tools/gen_character_creation_trial_boost.py; do not edit.",
        f"// Retail build {BUILD}, layout {LAYOUT_HASH}; source CSV SHA-256: {source_hash}.",
        f"// WoWDBDefs SHA-256: {definition_hash}.",
        "pub(crate) const RETAIL_CHARACTER_SERVICE_INFO_ROWS: &[(i32, i32, i32)] = &[",
    ]
    lines.extend(f"    ({service}, {boost}, {level})," for service, boost, level in rows)
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    rows, source_hash, definition_hash = read_export_rows()
    OUTPUT.write_text(
        render_rust(rows, source_hash, definition_hash),
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {len(rows)} {TABLE} rows for Retail {BUILD}")


if __name__ == "__main__":
    main()

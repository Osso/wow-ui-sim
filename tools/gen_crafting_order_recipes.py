#!/usr/bin/env python3
"""Project pinned 12.1.5.70391 CraftingOrder existence onto recipe spell IDs."""

import argparse
import csv
import hashlib
from pathlib import Path


def read_rows(path):
    with path.open(newline="", encoding="utf-8-sig") as source:
        return list(csv.DictReader(source))


def order_recipe_ids(orders, abilities):
    spells = {int(row["ID"]): int(row["Spell"]) for row in abilities}
    # Missing relations fail explicitly; never silently discard an order row.
    return sorted({spells[int(row["SkillLineAbilityID"])] for row in orders})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--crafting-order", type=Path, required=True)
    parser.add_argument("--skill-line-ability", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    recipes = order_recipe_ids(
        read_rows(args.crafting_order), read_rows(args.skill_line_ability)
    )
    lines = [
        "//! Generated by tools/gen_crafting_order_recipes.py; do not edit.",
        "//! PROVENANCE: CraftingOrder and SkillLineAbility 12.1.5.70391 enUS.",
    ]
    for name, path in [
        ("CraftingOrder", args.crafting_order),
        ("SkillLineAbility", args.skill_line_ability),
    ]:
        lines.append(f"//! {name} SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}")
    lines.extend([
        "//! Record equality with native build 70688 is UNKNOWN.",
        "//! Selection: any CraftingOrder row, joined by SkillLineAbility.ID to Spell.",
        "//! Field_10_0_2_46479_002 is not an eligibility filter.",
        "",
        "pub(super) static ORDER_RECIPE_IDS: &[i32] = &[",
    ])
    lines.extend(f"    {recipe}," for recipe in recipes)
    lines.extend(["];", ""])
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(recipes)} order-eligible recipes")


if __name__ == "__main__":
    main()

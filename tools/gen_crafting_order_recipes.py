#!/usr/bin/env python3
"""Project pinned 12.1.5.70391 CraftingOrder existence onto recipe spell IDs."""

import argparse
import csv
import hashlib
from pathlib import Path


CRAFTING_ORDER_SHA256 = "9e1927a2d39a8c1e7d49bc2c3cf4d670ce66591e2633d79038a73d83381030fd"
SKILL_LINE_ABILITY_SHA256 = "9f10fde1e657caad2c5d3a58919b39d096ac97f9f315031a6f161d8ba035a11c"


def read_pinned_rows(path, expected_hash):
    data = path.read_bytes()
    actual_hash = hashlib.sha256(data).hexdigest()
    if actual_hash != expected_hash:
        raise ValueError(
            f"{path}: pinned 12.1.5.70391 SHA256 mismatch: "
            f"expected {expected_hash}, got {actual_hash}"
        )
    return list(csv.DictReader(data.decode("utf-8-sig").splitlines()))


def order_recipe_ids(orders, abilities):
    spells = {int(row["ID"]): int(row["Spell"]) for row in abilities}
    # Missing relations fail explicitly; never silently discard an order row.
    return sorted({spells[int(row["SkillLineAbilityID"])] for row in orders})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--crafting-order", type=Path, required=True)
    parser.add_argument("--skill-line-ability", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    recipes = order_recipe_ids(
        read_pinned_rows(args.crafting_order, CRAFTING_ORDER_SHA256),
        read_pinned_rows(args.skill_line_ability, SKILL_LINE_ABILITY_SHA256),
    )
    lines = [
        "//! Generated by tools/gen_crafting_order_recipes.py; do not edit.",
        "//! PROVENANCE: CraftingOrder and SkillLineAbility 12.1.5.70391 enUS.",
    ]
    for name, digest in [
        ("CraftingOrder", CRAFTING_ORDER_SHA256),
        ("SkillLineAbility", SKILL_LINE_ABILITY_SHA256),
    ]:
        lines.append(f"//! {name} SHA256: {digest}")
    lines.extend([
        "//! Record equality with native build 70688 is UNKNOWN.",
        "//! Selection: any CraftingOrder row, joined by SkillLineAbility.ID to Spell.",
        "//! Field_10_0_2_46479_002 is not an eligibility filter.",
        "",
        "pub(super) static ORDER_RECIPE_IDS: &[i32] = &[",
    ])
    lines.extend(f"    {recipe}," for recipe in recipes)
    lines.extend(["];", ""])
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(recipes)} order-eligible recipes")


if __name__ == "__main__":
    main()

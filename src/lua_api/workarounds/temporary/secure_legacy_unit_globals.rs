pub(crate) fn copy_legacy_unit_globals_to_secureenv(lua: &mut rilua::Lua) -> LuaResult<()> {
    for &name in MASTER_SNAPSHOT_UNIT_GLOBALS {
        let function = LuaApiMut::get_global_val(lua, name);
        if !matches!(&function, Val::Function(_)) {
            return Err(runtime_error(format!(
                "master secureenv Unit global `{name}` is not a function in _G"
            )));
        }
        crate::lua_api::globals::security::set_secure_env_key_state(
            lua.state_mut(),
            name,
            function,
        )?;
    }
    Ok(())
}
